const test = require('node:test');
const assert = require('node:assert/strict');
const Roster = require('../js/roster.js');

// จำลองโครงสร้างไฟล์ "รายชื่อนักศึกษาลงทะเบียน" ของระบบทะเบียน (ชื่อสมมติ)
const rows = [
  ['มหาวิทยาลัยราชภัฏเชียงใหม่', '', '', 'รายชื่อนักศึกษาลงทะเบียน'],
  ['วิทยาเขต มหาวิทยาลัยราชภัฏเชียงใหม่  ภาคการศึกษา 2/2569'],
  ['ปริญญาตรี (4 ปี) ภาคปกติ'],
  ['รหัสวิชา  ARTD9999  คอมพิวเตอร์กราฟิกเพื่องานออกแบบ  หน่วยกิต  3(2-2-5)  Sec  01', '', '', '', '', '', '', '', 'ผู้สอน อาจารย์ ทดสอบ ระบบ'],
  ['วันเวลาเรียน พฤ. 08:00-12:00 1232-COM', '', '', '', '', '', '', '', 'วันเวลาสอบ F 16/02/27 08:00-10:00'],
  [],
  ['เลขที่', 'รหัสประจำตัว', 'ชื่อ', ' หมู่เรียน', 'สัปดาห์'],
  [' ', ' ', ' ', ' ', 1, 2, 3],
  [1, 69000001, 'นางสาวทดสอบ  หนึ่ง', 'ศอ 69.ศป.บ.4.1'],
  [2, '69000002', 'นายทดสอบ  สอง', 'ศอ 69.ศป.บ.4.1'],
  [3, '69000002', 'นายซ้ำ  ซ้ำ', 'ศอ 69.ศป.บ.4.1'],
  ['พิมพ์ ณ วันที่ 19/10/2569 1:53:27', '', '', '', '1/1']
];

test('parses course header and students', () => {
  const r = Roster.parse(rows);
  assert.deepEqual(r.course, {
    courseCode: 'ARTD9999', title: 'คอมพิวเตอร์กราฟิกเพื่องานออกแบบ', credits: '3(2-2-5)', section: '01',
    term: '2/2569', schedule: 'พฤ. 08:00-12:00 1232-COM', teacher: 'อาจารย์ ทดสอบ ระบบ'
  });
  assert.equal(r.students.length, 2);
  assert.deepEqual(r.students[0], { no: 1, studentId: '69000001', name: 'นางสาวทดสอบ หนึ่ง', group: 'ศอ 69.ศป.บ.4.1' });
});

test('rejects files that are not a roster', () => {
  assert.throws(() => Roster.parse([['hello']]), /รหัสวิชา/);
});
